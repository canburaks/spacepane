    public static func text(_ key: Key, languagePreferences: [String]? = nil) -> String {
        text(catalogKey: key.rawValue, languagePreferences: languagePreferences)
    }

    /// Catalog keys are technical metadata defined at the format registration boundary.
    public static func text(catalogKey: String, languagePreferences: [String]? = nil) -> String {
        let requested = localizedBundle(languagePreferences: languagePreferences).localizedString(forKey: catalogKey, value: nil, table: nil)
        if requested != catalogKey { return requested }
        let fallback = developmentBundle.localizedString(forKey: catalogKey, value: nil, table: nil)
        if fallback != catalogKey { return fallback }
        let unavailable = developmentBundle.localizedString(forKey: Key.resourceUnavailable.rawValue, value: "", table: nil)
        return unavailable == Key.resourceUnavailable.rawValue ? "" : unavailable
    }

    /// Call with a literal key (`.format(.someKey, …)`): validation discovers these call sites to check
    /// placeholder parity in every translation. `languagePreferences` selects a language for tests.
    public static func format(_ key: Key, arguments: [CVarArg], locale: Locale = .current,
                              languagePreferences: [String]? = nil) -> String {
        String(format: text(key, languagePreferences: languagePreferences), locale: locale, arguments: arguments)
    }

    /// Call with a literal key (`.count(.someKey, …)`) for a plural catalog entry: validation requires one.
    /// `value` is the first format argument, which the generated `.stringsdict` uses to select the plural
    /// category; every variant prints the second, `value` formatted for `locale`, so digits and grouping
    /// follow the locale and no translation carries digits of its own. Never show a count through a bare `%lld`.
    /// Additional template arguments begin at position three; preformat any other counts for the same locale.
    public static func count(_ key: Key, _ value: Int, additionalArguments: [CVarArg] = [],
                             locale: Locale = .current,
                             languagePreferences: [String]? = nil) -> String {
        let formatted: String = value.formatted(.number.locale(locale))
        let arguments: [CVarArg] = [Int64(value), formatted] + additionalArguments
        return String(format: text(key, languagePreferences: languagePreferences), locale: locale, arguments: arguments)
    }

    private static var developmentBundle: Bundle {
        guard let path = RendererResources.bundle.path(forResource: "en", ofType: "lproj"),
              let bundle = Bundle(path: path) else { return RendererResources.bundle }
        return bundle
    }

    private static func localizedBundle(languagePreferences: [String]?) -> Bundle {
        // Language selection follows the hosting process; region formatting remains independent.
        guard let languagePreferences else { return RendererResources.bundle }
        let matches = Bundle.preferredLocalizations(from: RendererResources.bundle.localizations, forPreferences: languagePreferences)
        guard let match = matches.first,
              let path = RendererResources.bundle.path(forResource: match, ofType: "lproj"),
              let bundle = Bundle(path: path) else { return developmentBundle }
        return bundle
    }
