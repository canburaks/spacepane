#!/usr/bin/env python3
"""Regenerate Packages/PreviewCore/Tests/PreviewFormatsTests/Archives/ThirdPartyArchiveVectors.swift.

These 7z archives are written by py7zr, an independent implementation, so the reader is checked
against a writer other than this repository's own fixture builder. py7zr is a test-time tool only: it is
not a dependency of the product and its code is never copied. Run it from a virtual environment:

    python3 -m venv .build/py7zr-venv && .build/py7zr-venv/bin/pip install py7zr
    .build/py7zr-venv/bin/python script/generate_archive_third_party_vectors.py

The source tree is synthetic. Modification times other than hello.txt follow the clock at generation
time, so the Swift tests assert only names, kinds, sizes and encryption flags. The committed file is the
reference; regenerating changes the embedded bytes.
"""
from __future__ import annotations

import base64
import os
from pathlib import Path
import shutil
import sys
import tempfile

import py7zr

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'Packages/PreviewCore/Tests/PreviewFormatsTests/Archives/ThirdPartyArchiveVectors.swift'
VARIANTS = [
    ('lzmaMembers', {}),
    ('bzip2Members', {'filters': [{'id': py7zr.FILTER_BZIP2}]}),
    ('encryptedMembers', {'password': 'synthetic-password'}),
    ('encryptedHeader', {'password': 'synthetic-password', 'header_encryption': True}),
]


def main() -> None:
    with tempfile.TemporaryDirectory() as temporary:
        source = Path(temporary) / 'src'
        (source / 'docs/deep').mkdir(parents=True)
        (source / 'hello.txt').write_text('hello world\n' * 20)
        (source / 'docs/notes.md').write_text('# Notes\n' + 'abc ' * 100)
        (source / 'docs/deep/empty.txt').write_text('')
        (source / 'docs/deep/data.bin').write_bytes(bytes(range(256)) * 4)
        os.utime(source / 'hello.txt', (1_767_225_600, 1_767_225_600))
        lines = ['// Generated by script/generate_archive_third_party_vectors.py (py7zr). Do not edit by hand.\n',
                 '// Source tree: src/hello.txt (240 bytes), src/docs/notes.md (408), src/docs/deep/empty.txt (0),\n',
                 '// src/docs/deep/data.bin (1024) and the directories src, src/docs, src/docs/deep.\n',
                 'import Foundation\n\nenum ThirdPartyArchiveVectors {\n']
        for name, options in VARIANTS:
            path = Path(temporary) / f'{name}.7z'
            with py7zr.SevenZipFile(path, 'w', **options) as archive:
                archive.writeall(source, 'src')
            encoded = base64.b64encode(path.read_bytes()).decode('ascii')
            lines.append(f'    static let {name} = Data(base64Encoded: "{encoded}")!\n')
        lines.append('}\n')
    OUTPUT.write_text(''.join(lines))
    print(f'Wrote {OUTPUT.relative_to(ROOT)} using py7zr {py7zr.__version__}.')


if __name__ == '__main__':
    sys.exit(main())
