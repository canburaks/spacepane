#!/usr/bin/env python3
"""Regenerate Packages/PreviewCore/Tests/PreviewFormatsTests/Archives/ArchiveTestVectors.swift.

The LZMA and LZMA2 decoders are checked against raw streams made by liblzma through Python's
`lzma` module (`FORMAT_RAW`), and the 7z, RAR and bzip2 readers against containers built by
script/archive_fixtures.py. Plain texts are synthetic and deterministic. Run:

    python3 script/generate_archive_test_vectors.py

Each vector is verified by decompressing it again here before it is written, so a stale or
corrupted vector fails at generation time instead of in the Swift tests. The multi-block xz vector needs
the `xz` command-line tool on PATH. The output depends on
the installed liblzma only for the compressed bytes; the committed file is the reference.
"""
from __future__ import annotations

import base64
import bz2
import lzma
from pathlib import Path
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import archive_fixtures as fixtures  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'Packages/PreviewCore/Tests/PreviewFormatsTests/Archives/ArchiveTestVectors.swift'


def text(lines: int) -> bytes:
    return ''.join(f'line {i}: the quick brown fox jumps over the lazy dog {i * i}\n' for i in range(lines)).encode()


def noise(count: int) -> bytes:
    """Deterministic incompressible-looking bytes (a 32-bit linear congruential generator)."""
    state = 0x12345678
    out = bytearray()
    for _ in range(count):
        state = (state * 1664525 + 1013904223) & 0xFFFFFFFF
        out.append(state >> 24)
    return bytes(out)


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode('ascii')


def lzma1(plain: bytes, lc: int, lp: int, pb: int, dictionary: int) -> bytes:
    raw = lzma.compress(plain, format=lzma.FORMAT_RAW, filters=[
        {'id': lzma.FILTER_LZMA1, 'dict_size': dictionary, 'lc': lc, 'lp': lp, 'pb': pb}])
    check = lzma.decompress(raw, format=lzma.FORMAT_RAW, filters=[
        {'id': lzma.FILTER_LZMA1, 'dict_size': dictionary, 'lc': lc, 'lp': lp, 'pb': pb}])
    assert check == plain
    return raw


def lzma2(plain: bytes, dictionary: int) -> bytes:
    filters = [{'id': lzma.FILTER_LZMA2, 'dict_size': dictionary}]
    raw = lzma.compress(plain, format=lzma.FORMAT_RAW, filters=filters)
    assert lzma.decompress(raw, format=lzma.FORMAT_RAW, filters=filters) == plain
    return raw


def swift_data(label: str, data: bytes) -> str:
    return f'    static let {label} = Data(base64Encoded: "{b64(data)}")!\n'


def main() -> None:
    out = ['// Generated by script/generate_archive_test_vectors.py. Do not edit by hand.\n',
           '// Raw LZMA/LZMA2 streams come from liblzma (Python lzma, FORMAT_RAW); containers come from\n',
           '// script/archive_fixtures.py. All content is synthetic.\n',
           'import Foundation\n\n',
           'struct LZMAVector {\n',
           '    let name: String\n    let lc: Int, lp: Int, pb: Int\n    let dictionary: Int\n',
           '    let compressed: Data\n    let plain: Data\n}\n\n',
           'enum ArchiveTestVectors {\n']
    out.append('    static let lzma1: [LZMAVector] = [\n')
    for name, plain, lc, lp, pb, dictionary in [
        ('text defaults', text(24), 3, 0, 2, 1 << 16),
        ('literals lc0 lp2 pb0', noise(300) + text(6), 0, 2, 0, 1 << 16),
        ('lc4 lp0 pb4', text(12) + noise(80), 4, 0, 4, 1 << 20),
        ('lc1 lp3 pb1', text(10), 1, 3, 1, 1 << 16),
        ('long repeats', b'ab' * 4000 + b'tail', 3, 0, 2, 1 << 16),
    ]:
        raw = lzma1(plain, lc, lp, pb, dictionary)
        out.append(f'        LZMAVector(name: "{name}", lc: {lc}, lp: {lp}, pb: {pb}, dictionary: {dictionary},\n'
                   f'                   compressed: Data(base64Encoded: "{b64(raw)}")!,\n'
                   f'                   plain: Data(base64Encoded: "{b64(plain)}")!),\n')
    out.append('    ]\n\n')
    out.append('    /// (name, dictionary property byte, compressed, plain)\n')
    out.append('    static let lzma2: [(name: String, property: UInt8, compressed: Data, plain: Data)] = [\n')
    for name, plain, dictionary in [
        ('stored then coded chunks', noise(300) + text(40), 1 << 16),
        ('text', text(120), 1 << 20),
        ('empty-ish', b'x', 1 << 16),
    ]:
        raw = lzma2(plain, dictionary)
        out.append(f'        (name: "{name}", property: {fixtures.lzma2_property(dictionary)},\n'
                   f'         compressed: Data(base64Encoded: "{b64(raw)}")!,\n'
                   f'         plain: Data(base64Encoded: "{b64(plain)}")!),\n')
    out.append('    ]\n\n')
    entries = fixtures.SAMPLE_ENTRIES
    out.append('    // 7z containers over the entries Example/, Example/readme.txt, Example/data/values.json, Example/notes.md.\n')
    out.append(swift_data('sevenZipPlainHeader', fixtures.sevenzip_archive(entries)))
    out.append(swift_data('sevenZipLZMAHeader', fixtures.sevenzip_archive(entries, header_coder='lzma')))
    out.append(swift_data('sevenZipLZMA2Header', fixtures.sevenzip_archive(entries, header_coder='lzma2')))
    out.append(swift_data('sevenZipEncryptedHeader', fixtures.sevenzip_archive(entries, header_coder='aes')))
    out.append('\n    // bzip2 streams: a TAR of the sample entries, text, binary and two concatenated streams.\n')
    out.append(swift_data('bzip2TAR', bz2.compress(fixtures.tar_bytes(entries))))
    out.append(swift_data('bzip2Text', bz2.compress('first line\npassword=synthetic-secret-value\n日本語\n'.encode())))
    out.append(swift_data('bzip2Binary', bz2.compress(bytes([0, 255, 0, 1, 2]))))
    out.append(swift_data('bzip2Concatenated', bz2.compress(b'first\n') + bz2.compress(b'second\n')))
    out.append(swift_data('bzip2Bomb', bz2.compress(b'A' * (8 << 20))))
    out.append('\n    // xz streams with the single-LZMA2 filter layout the xz reader accepts.\n')
    out.append(swift_data('xzTAR', fixtures.xz_bytes(fixtures.tar_bytes(entries))))
    out.append(swift_data('xzText', fixtures.xz_bytes('first line\npassword=synthetic-secret-value\n日本語\n'.encode())))
    out.append(swift_data('xzBinary', fixtures.xz_bytes(bytes([0, 255, 0, 1, 2]))))
    # Preset 9 records a 64 MiB dictionary in the block header even for tiny inputs; those streams are
    # decoded by the bounded LZMA2 path. `xzHugeDictionary` asks for 128 MiB and must be declined.
    plain = text(30)
    out.append(swift_data('xzLargeDictionaryPlain', plain))
    for label, check in [('CRC32', lzma.CHECK_CRC32), ('CRC64', lzma.CHECK_CRC64), ('SHA256', lzma.CHECK_SHA256), ('NoCheck', lzma.CHECK_NONE)]:
        packed = lzma.compress(plain, format=lzma.FORMAT_XZ, check=check, preset=9)
        assert lzma.decompress(packed) == plain
        out.append(swift_data(f'xzLargeDictionary{label}', packed))
    huge = lzma.compress(b'x' * 100, format=lzma.FORMAT_XZ, filters=[{'id': lzma.FILTER_LZMA2, 'dict_size': 128 << 20}])
    out.append(swift_data('xzHugeDictionary', huge))
    # Several blocks, as written by multithreaded or block-limited xz, with a CRC64 check.
    blocks = subprocess.run(['xz', '-9', '--block-size=700', '--check=crc64', '-c'], input=plain, capture_output=True, check=True).stdout
    assert lzma.decompress(blocks) == plain
    out.append(swift_data('xzMultiBlockLargeDictionary', blocks))
    out.append('}\n')
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(''.join(out))
    print(f'Wrote {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size} bytes).')


if __name__ == '__main__':
    main()
